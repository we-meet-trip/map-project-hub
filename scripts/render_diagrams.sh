#!/usr/bin/env bash
# docs/diagrams/src 의 원본에서 라이트·다크 SVG 와 PNG 를 모두 다시 만든다.
# 필요: Graphviz(dot), rsvg-convert(librsvg), python3. 폰트 Pretendard 가 있으면 그대로 쓰인다.
# 쓰임: scripts/render_diagrams.sh
set -euo pipefail

cd "$(dirname "$0")/.."
SRC=docs/diagrams/src
OUT=docs/diagrams

# 팔레트(라이트 / 다크): 배경·글자·선, 서비스 노드, 저장소, 외부 서비스, 선택 기능(기본 꺼짐)
palette() {
  case "$1" in
    light) echo 's/@BG@/#FFFFFF/g;s/@FG@/#1F2328/g;s/@LINE@/#57606A/g;s/@SVC_FILL@/#DDF4FF/g;s/@SVC_EDGE@/#0969DA/g;s/@DB_FILL@/#FFF8C5/g;s/@DB_EDGE@/#9A6700/g;s/@EXT_FILL@/#F6F8FA/g;s/@EXT_EDGE@/#57606A/g;s/@OPT_FILL@/#FBEFFF/g;s/@OPT_EDGE@/#8250DF/g' ;;
    dark)  echo 's/@BG@/#0D1117/g;s/@FG@/#E6EDF3/g;s/@LINE@/#8B949E/g;s/@SVC_FILL@/#0C2D6B/g;s/@SVC_EDGE@/#58A6FF/g;s/@DB_FILL@/#3B2E00/g;s/@DB_EDGE@/#D29922/g;s/@EXT_FILL@/#161B22/g;s/@EXT_EDGE@/#8B949E/g;s/@OPT_FILL@/#2B1D3D/g;s/@OPT_EDGE@/#A371F7/g' ;;
  esac
}

for src in "$SRC"/*.dot; do
  [ -e "$src" ] || continue
  name=$(basename "$src" .dot)
  for theme in light dark; do
    # Graphviz 는 SVG 머리에 판·빌드 시각 주석을 넣는다. 결과물에 남기지 않는다.
    sed -e "$(palette "$theme")" "$src" | dot -Tsvg \
      | sed -e '/^<!-- Generated by graphviz/,/-->/d' > "$OUT/$name-$theme.svg"
    rsvg-convert -w 1600 "$OUT/$name-$theme.svg" -o "$OUT/$name-$theme.png"
  done
done

for src in "$SRC"/*.seq.json; do
  [ -e "$src" ] || continue
  name=$(basename "$src" .seq.json)
  python3 scripts/seq.py "$src" "$OUT/$name"
  for theme in light dark; do
    rsvg-convert -w 1600 "$OUT/$name-$theme.svg" -o "$OUT/$name-$theme.png"
  done
done

echo "rendered: $(ls "$OUT"/*.svg | wc -l | tr -d ' ') svg, $(ls "$OUT"/*.png | wc -l | tr -d ' ') png"
